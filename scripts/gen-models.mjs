#!/usr/bin/env node
/**
 * Generator of src/models.ts (from models/models.json) and src/effects.ts
 * (from models/definitions.json).
 *
 * Why a generator instead of importing the JSON at runtime: after building into
 * dist/, reading a file next to the bundle adds extra coupling (and another way
 * to fail in someone else's environment). The tables are small, so they are
 * baked right into the code.
 *
 *   node scripts/gen-models.mjs && npx prettier --write src/models.ts src/effects.ts
 */

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const source = JSON.parse(readFileSync(join(root, "models", "models.json"), "utf8"))

if (!Array.isArray(source) || source.length === 0) {
    throw new Error("models/models.json: expected a non-empty array of models")
}

// --- src/models.ts --------------------------------------------------------

const header = `/**
 * Registry of known BLE LED-strip controllers.
 *
 * Data comes from models.json of the Home Assistant integration
 * https://github.com/dave-code-ruiz/elkbledom (MIT).
 * It is pinned here statically to avoid pulling in HA and reading a file at
 * runtime (which matters after building into dist/).
 *
 * AUTOGENERATED FILE: edit models/models.json instead, then rebuild with
 * \`npm run gen:models\`.
 */

/** Placeholders in command templates. */
export type Placeholder = "r" | "g" | "b" | "i" | "v" | "w" | "c";
export type Byte = number | Placeholder;
export type Template = Byte[];

export interface ModelCommands {
    turn_on?: Template;
    turn_off?: Template;
    color?: Template;
    white?: Template;
    brightness?: Template;
    effect?: Template;
    effect_speed?: Template;
    color_temp?: Template;
    query?: Template;
    [key: string]: Template | undefined;
}

export interface ModelSpec {
    /** Name as it appears on air (compared by prefix). */
    name: string;
    /** Write characteristic for commands. */
    write_uuid: string;
    /** Notify characteristic (may be absent). */
    read_uuid?: string;
    /** Pause between commands, ms (requirements differ between models). */
    settle_ms?: number;
    commands: ModelCommands;
    color_temp_range?: { min_kelvin: number; max_kelvin: number };
    effect_range?: { min: number; max: number };
    effect_speed_range?: { min: number; max: number };
    effects_class?: string;
    effects_list?: string;
    /** Matches the write characteristic handle, when that matters for disambiguation. */
    handle?: number;
}

/** Default pause, if a model does not define one. */
const SETTLE_DEFAULT = 150;

/** Known pause requirements (from the elkbledom.py integration). */
const SETTLE_BY_NAME: Record<string, number> = {
    "ELK-BLEDOB": 100,
    "ELK-BLEDDM": 300,
};

export const MODELS: ModelSpec[] = `

const footer = `
/** Pause between commands for a specific model. */
export function settleMsFor(modelName: string): number {
    return SETTLE_BY_NAME[modelName] ?? SETTLE_DEFAULT;
}
`

const body = JSON.stringify(source, null, 4)
    .split("\n")
    .map((line) => line)
    .join("\n")

writeFileSync(join(root, "src", "models.ts"), `${header}${body};\n${footer}`, "utf8")
console.log(`src/models.ts updated: ${source.length} models`)

// --- src/effects.ts ---------------------------------------------------------

const definitions = JSON.parse(readFileSync(join(root, "models", "definitions.json"), "utf8"))
const effectsDefinitions = definitions.effects_definitions ?? {}
const effectsLists = definitions.effects_lists ?? {}

/**
 * Ordered name → index entries for one effects class.
 *
 * The display order of the phone app lives in effects_lists; the authoritative
 * name → value mapping lives in effects_definitions. The list comes first (it
 * is what the user sees in the app), then everything else by index. A list
 * name without a value cannot be put on the wire, so it is skipped.
 */
function effectsFor(className) {
    const defs = effectsDefinitions[className] ?? {}
    const listName = className.replace(/^EFFECTS/, "EFFECTS_list")
    const list = effectsLists[listName] ?? []
    const entries = []
    const seen = new Set()
    for (const name of list) {
        if (!(name in defs) || seen.has(name)) continue
        entries.push({ name, index: defs[name] })
        seen.add(name)
    }
    const rest = Object.keys(defs)
        .filter((name) => !seen.has(name))
        .sort((a, b) => defs[a] - defs[b])
    for (const name of rest) entries.push({ name, index: defs[name] })
    return entries
}

const classNames = Object.keys(effectsDefinitions).sort()

const effectsHeader = `/**
 * Effect catalogs per controller family.
 *
 * The controllers are write-only: over Bluetooth they never report which
 * effects they support or what the effect numbers mean. These name → index
 * tables were reverse-engineered from the phone apps and pinned from
 * definitions.json of the Home Assistant integration
 * https://github.com/dave-code-ruiz/elkbledom (MIT).
 *
 * AUTOGENERATED FILE: edit models/definitions.json instead, then rebuild with
 * \`npm run gen:models\`.
 */

/** One named effect: a readable name plus the value that goes into the packet. */
export interface EffectDef {
    /** Effect name, as in the phone apps (e.g. "blink_red"). */
    name: string;
    /** Value of the effect byte in the effect packet. */
    index: number;
}
`

const classesBody = classNames
    .map((className) => {
        const entries = effectsFor(className)
            .map((entry) => `        { name: ${JSON.stringify(entry.name)}, index: ${entry.index} },`)
            .join("\n")
        return `    ${JSON.stringify(className)}: [\n${entries}\n    ],`
    })
    .join("\n")

const effectsBody = `
/** All known effect catalogs: effects_class → named effects (app order). */
export const EFFECTS: Record<string, readonly EffectDef[]> = {
${classesBody}
}

/** Known effects_class names. */
export const EFFECT_CLASS_NAMES = ${JSON.stringify(classNames, null, 4).replace(/\n/g, "\n")} as const;

/** Effects of a class; an unknown class gets an empty list. */
export function effectsForClass(className?: string): readonly EffectDef[] {
    return className ? (EFFECTS[className] ?? []) : [];
}
`

writeFileSync(join(root, "src", "effects.ts"), `${effectsHeader}${effectsBody}`, "utf8")
const total = classNames.reduce((count, className) => count + effectsFor(className).length, 0)
console.log(`src/effects.ts updated: ${classNames.length} classes, ${total} effects`)
